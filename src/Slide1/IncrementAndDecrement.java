package Slide1;

public class IncrementAndDecrement {
    public static void main(String[] args) {
        int a = 1;
        System.out.println("++a : " + ++a);
        System.out.println("a   : " + a);
        System.out.println("a++ : " + a++);
        System.out.println("--a : " + --a);
        System.out.println("a-- : " + a--);
    }
}